# ------------------------------------------------------------------ helpers
def txt(t, x, y, size=14, color=INK, weight="700", anchor="middle"):
    return (f'<text x="{x:.1f}" y="{y:.1f}" text-anchor="{anchor}" font-size="{size}" '
            f'font-weight="{weight}" fill="{color}">{t}</text>')


def pill(t, x, y, w, h, fill="#fff", stroke=None, color=INK, size=18, dashed=False,
         min_size=8):
    """قرص مستدير بنص — يُصغّر الخط تلقائيًا إن كان النص أطول من الصندوق."""
    stroke = stroke or C["gray"]
    da = ' stroke-dasharray="6 4"' if dashed else ""
    size = fit_font(t, w - 14, size, min_size=min_size)
    r = min(h / 2, 14)
    return (f'<rect x="{x}" y="{y}" width="{w}" height="{h}" rx="{r}" fill="{fill}" '
            f'stroke="{stroke}" stroke-width="2.5"{da}/>'
            + txt(t, x + w / 2, y + h / 2 + size * 0.36, size=size, color=color))



def opts_block(opts, y, W, pad=20, h=40, gap=7):
    """خيارات: صف أفقي إن كانت قصيرة، وإلا قائمة رأسية بعرض كامل."""
    o = []
    if opts and max(len(x) for x in opts) <= 13:
        n = len(opts)
        gw = 10
        bw = (W - 2 * pad - (n - 1) * gw) / n
        for i, op in enumerate(opts):
            o.append(pill(op, pad + i * (bw + gw), y, bw, h, "#fff", C["gray"], INK, 14))
        return "".join(o), h
    for i, op in enumerate(opts or []):
        o.append(pill(op, pad, y + i * (h + gap), W - 2 * pad, h, "#fff", C["gray"], INK, 14))
    return "".join(o), (len(opts) * (h + gap) - gap if opts else 0)


def pair_fig(a, b, opts=None):
    W = 520
    oh = 0
    if opts:
        _, oh = opts_block(opts, 0, W)
    H = 130 + oh + (16 if opts else 0)
    o = [box(0, 0, W, H, fill="#fbfcff", stroke=C["gray"], sw=2, radius=14),
         txt("ما العلاقة / أوجه الشبه؟", W - 22, 32, size=15, color=C["gray"], anchor="end")]
    o.append(pill(a, 20, 46, 210, 58, "#eef4ff", C["blue"], C["blue"], 21))
    o.append(txt("↔", 241, 86, size=22, color=C["gray"]))
    o.append(pill(b, 268, 46, 210, 58, "#eef4ff", C["blue"], C["blue"], 21))
    if opts:
        o.append(opts_block(opts, 120, W)[0])
    return svg(W, H, "".join(o))


def analogy_fig(a, b, c, opts):
    W = 470
    oh = opts_block(opts, 0, W)[1]
    H = 206 + oh + 14
    o = [box(0, 0, W, H, fill="#fbfcff", stroke=C["gray"], sw=2, radius=14),
         txt("أكمل العلاقة على نفس النمط", W - 22, 28, size=15, color=C["gray"], anchor="end")]
    o.append(pill(a, 18, 42, 190, 56, "#eef4ff", C["blue"], C["blue"], 21))
    o.append(txt(":", 220, 80, size=24, color=C["gray"]))
    o.append(pill(b, 240, 42, 190, 56, "#eef4ff", C["blue"], C["blue"], 21))
    o.append(txt("::", 232, 126, size=19, color=C["purple"]))
    o.append(pill(c, 18, 134, 190, 56, "#f3ecff", C["purple"], C["purple"], 21))
    o.append(txt(":", 220, 172, size=24, color=C["gray"]))
    o.append(pill("؟", 240, 134, 190, 56, "#fff0f3", C["red"], C["red"], 24, dashed=True))
    o.append(opts_block(opts, 200, W, pad=18)[0])
    return svg(W, H, "".join(o))


def text_fig(lines, opts=None, label=None):
    W = 560
    lh = 32
    oh = opts_block(opts, 0, W)[1]
    H = 26 + lh * len(lines) + (oh + 14 if opts else 0) + 22
    o = [box(0, 0, W, H, fill="#fbfcff", stroke=C["gray"], sw=2, radius=14)]
    if label:
        o.append(txt(label, W - 22, 26, size=15, color=C["gray"], anchor="end"))
    y = 30 + (16 if label else 4)
    for ln in lines:
        fsz = fit_font(ln, W - 48, 19, min_size=10)
        o.append(txt(ln, W - 24, y + 22, size=fsz, color=INK, anchor="end"))
        y += lh
    if opts:
        o.append(opts_block(opts, y + 4, W)[0])
    return svg(W, H, "".join(o))


def legend(pairs):
    n = len(pairs)
    W, H = 30 + n * 118, 104
    o = [box(0, 0, W, H, fill="#ffffff", stroke=C["gray"], sw=2, radius=12),
         txt("مفتاح الرموز", W - 14, 22, size=13, color=C["gray"], anchor="end")]
    for i, (kind, word) in enumerate(pairs):
        cx = 30 + i * 118 + 40
        o.append(shape(kind, cx, 50, 24, fill="#fff", stroke=C["blue"], sw=2.6))
        o.append(txt(word, cx, 88, size=15, color=INK))
    return svg(W, H, "".join(o))


def nested(outer, mid, inner, cap="الشكل المطلوب"):
    W, H = 250, 224
    cx, cy = 125, 104
    o = [box(0, 0, W, H, fill="#fbfcff", stroke=C["gray"], sw=2, radius=14)]
    o.append(shape(outer, cx, cy, 74, fill="#eef4ff", stroke=C["blue"], sw=3))
    o.append(shape(mid, cx, cy, 50, fill="#f3ecff", stroke=C["purple"], sw=3))
    o.append(shape(inner, cx, cy, 28, fill="#eafaf1", stroke=C["green"], sw=3))
    o.append(txt(cap, W - 16, 210, size=13, color=C["gray"], anchor="end"))
    return svg(W, H, "".join(o))


