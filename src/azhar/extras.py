def _rot(lst, i):
    if not lst:
        return []
    i %= len(lst)
    return lst[i:] + lst[:i]


def _pick(pool, bad, i, n=3, pad=()):
    c = []
    for x in list(pool) + list(pad):
        if x != bad and x not in c:
            c.append(x)
    return _rot(c, i)[:n]


