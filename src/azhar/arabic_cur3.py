def _rot(lst, i):
    if not lst:
        return []
    i %= len(lst)
    return lst[i:] + lst[:i]


def _pick(pool, bad, i, n=3, pad=()):
    c = []
    for x in list(pool) + list(pad):
        if x != bad and x not in c:
            c.append(x)
    return _rot(c, i)[:n]


def bank():
    out = []
    allm = [m for _, m, _ in MASDAR]

    # (١) المصادر
    for i, (v, m, rule) in enumerate(MASDAR):
        q = mk(f"ما مصدر الفعل «{v}»؟", m, _pick(allm, m, i * 2),
               f"«{v}» على وزن {rule}، فمصدره «{m}».", S, "الصرف — المصادر", SRC_HOT, 2)
        if q:
            out.append(q)
        q = mk(f"«{m}» مصدرٌ للفعل:", v, _pick([x for x, _, _ in MASDAR], v, i * 3),
               f"المصدر «{m}» من الفعل «{v}» ({rule}).", S, "الصرف — المصادر", SRC_CUR, 1)
