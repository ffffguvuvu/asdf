# ===================== الإملاء والترقيم =====================
("لماذا رُسمت الهمزة على الواو في «فؤاد»؟",
 "لأنها همزة متوسطة مفتوحة وما قبلها مضموم، والضمة أقوى من الفتحة",
 "فيُنظر في المتوسطة إلى أقوى الحركتين: حركتِها وحركةِ ما قبلها، وترتيبُ القوّة: الكسرة ثم الضمة ثم الفتحة ثم السكون."),

("في أيّ حالةٍ لا تُكتب الهمزة المتوسطة على الألف؟",
 "إذا كانت مضمومة وما قبلها مفتوح، فتُكتب على الواو",
 "لأن الضمة أقوى من الفتحة فتغلبها، وأما إذا كانت مفتوحةً وما قبلها مفتوح أو ساكن، أو ساكنةً وما قبلها مفتوح، فتُكتب على الألف."),

("لماذا كُتبت همزة «عبء» على السطر؟",
 "لأنها متطرفة وما قبلها ساكن",
 "والساكن لا حركة له تُناسب حرفًا من حروف العلّة، فبقيت الهمزة مفردةً على السطر، وهذا هو الضابط في «جزء، دفء، بطء»."),

("كيف يُنوَّن «عبء» في حالة النصب؟",
 "عِبئًا",
 "لأن التنوين حرَّك ما قبل الهمزة بالفتح فصارت متوسّطةً حكمًا، والمتوسطةُ المفتوحة بعد ساكنٍ صحيح تُكتب على نبرةٍ إذا أمكن الوصل."),

("«ايم الله» — همزة قطع أم ألف وصل؟",
 "ألف وصل، لأنها من الأسماء العشرة المسموعة",
 "وهي: ابن، ابنة، اسم، است، امرؤ، امرأة، اثنان، اثنتان، ايمُ الله، ايمُنُ الله. وما عداها من الأسماء فهمزتُه قطع."),

("«اقرأ» — لماذا بُدئت بألف وصل؟",
 "لأنها أمرٌ من فعلٍ ثلاثيّ، وأمرُ الثلاثي همزتُه وصل",
 "وضابطُ ألف الوصل في الأفعال: أمرُ الثلاثي، وماضي الخماسي والسداسي وأمرُهما ومصدرُهما. وما عداه فهمزةُ قطع."),

("«اتقِ الله وأَتقِن عملك» — ما نوع الهمزة في كلٍّ منهما؟",
 "«اتقِ» ألف وصل لأنه أمر من خماسيّ، و«أتقِن» همزة قطع لأنه أمر من رباعيّ",
 "فالخماسيُّ «اتّقى» همزتُه وصل، والرباعيُّ «أتقن» همزتُه قطع، والفارقُ عددُ حروف الماضي لا صورةُ الأمر."),

("ما علامة الترقيم المناسبة بعد «قال المعلم»؟",
 "النقطتان الرأسيتان",
 "لأنهما تُوضعان قبل القول المحكيّ وقبل التفصيل بعد الإجمال وقبل التعداد، فهما علامةُ ما يأتي بعدهما مفسِّرًا لما قبلهما."),

("«محمد أخي ... وفّقه الله ... متفوّقٌ في دراسته» — ما العلامة المناسبة؟",
 "الشرطتان، لأن الجملة بينهما اعتراضية",
 "والشرطة تُوضع في أول الجملة الاعتراضية وآخرها لتفصلها عمّا قبلها وبعدها، فتبقى الجملة الأصلية متّصلةَ المعنى."),

("«ما أجملَ السماء» — ما علامة الترقيم؟ ولماذا؟",
 "علامة التعجّب",
 "لأن الأسلوب تعجّبٌ قياسيّ على وزن «ما أفعلَه»، وعلامةُ التعجّب تُوضع بعد التعجّب والدعاء والإغراء والتحذير والمدح والذمّ."),

("ما نوع اللام في «المعلّم» وفي «الطالب»؟",
 "في «المعلّم» قمرية، وفي «الطالب» شمسية",
 "لأن الميم من الحروف القمرية فتُنطق اللام ظاهرةً، والطاءُ من الشمسية فتُدغم فيها اللام وتُشدَّد، والميزانُ النطقُ لا الرسم."),

# ===================== المعاني والمفردات =====================
("ما معنى «شُمّ العرانين»؟",
 "أعزّة أُباة، أصحاب عزّةٍ وأنفة",
 "والعِرنين أصلُ الأنف، والشَّمَمُ ارتفاعُه، فكُنّي بارتفاع الأنف عن العزّة والإباء، وهي كنايةٌ عن صفةٍ جرت مجرى المثل."),

("ما معنى «البتول»؟",
 "العذراء المنقطعة عن الرجال",
 "وأصل البَتْل القطعُ، ومنه «تبتَّل إليه تبتيلًا» أي انقطع للعبادة، فالوصفُ راجعٌ إلى معنى الانقطاع في مادّة اللفظ."),

("ما معنى «حصيف»؟",
 "عاقلٌ جيّد الرأي، محكمُ العقل",
 "وأصله من إحصاف الأمر أي إحكامه، فالحصيفُ من أُحكم عقلُه فلا يتسرّب إليه الخلل، وهذا أدقُّ من ترجمته بـ«ذكي»."),

("ما معنى «سرمديّ»؟",
 "دائمٌ أبديّ لا ينقطع",
 "والسَّرمد في اللغة دوامُ الزمان المتّصل الذي لا يتخلّله ليلٌ ولا نهار، فهو أبلغُ من «دائم» لأنه ينفي الانقطاع أصلًا."),

("ما الفرق بين «مُقِيت» و«مَقِيت»؟",
 "«مُقِيت» بالضمّ: المقتدر. و«مَقِيت» بالفتح: البغيض",
 "فالأولى من القوت أي الحفظ والاقتدار، ومنه «وكان الله على كل شيء مُقِيتًا». والثانية من المقت وهو البغض الشديد."),

("ما معنى «أفّاك»؟",
 "كذّابٌ مبالغ في الكذب",
 "و«أفّاك» صيغةُ مبالغة على وزن «فَعّال» من الإفك وهو أسوأُ الكذب، فدلّت الصيغةُ على كثرة الوقوع فيه لا على مجرّد وقوعه."),

("ما معنى «اليراع»؟",
 "القلم",
 "وأصل اليَراع القصبُ الأجوف، ولمّا كانت الأقلام تُتّخذ منه سُمّي القلم باسمه، وهذه علاقةُ المادّة في المجاز المرسل."),

("ما معنى «أريحيّ»؟",
 "واسعُ الخُلُق، نشيطٌ إلى فعل المعروف",
 "وأصله من الارتياح وهو خفّةُ النفس إلى الخير، فالأريحيُّ من تهتزّ نفسُه للمعروف طربًا، وهو أبلغ من «كريم» لأنه يصف الطبع."),

("ما معنى «صَلِف»؟",
 "متكبّر متعجرف",
 "والصَّلَف في أصل اللغة ادّعاءُ المرء فوق ما عنده، فهو أخصُّ من مطلق الكِبر لأنه كبرٌ مبنيّ على دعوى باطلة."),

("ما معنى «زَنِخ»؟",
 "فاسدٌ متغيّرُ الرائحة",
 "ويُستعمل أصلًا في الدهن والسَّمن إذا تغيّر طعمُه وريحُه بطول المكث، ثم توسّع فيه فأُطلق على كل فاسدٍ منتن."),

("ما معنى «قانع»؟ وما معنى «دامس»؟",
 "القانع: الراضي بما قُسم له. والدامس: الشديد الظلام",
 "والقناعةُ رضًا بالموجود لا طلبٌ للمفقود، والدَّمْسُ في اللغة التغطيةُ والستر، فسُمّي الظلام الشديد دامسًا لأنه يستر ما تحته."),

("ما معنى «شائن» وما معنى «ماجن»؟",
 "الشائن: القبيح المُخجِل. والماجن: الهازل القليل الحياء",
 "فالشَّيْنُ ضدُّ الزَّيْن، والمجونُ أن يستهتر المرء فلا يُبالي بما قال ولا بما قيل فيه، فالأول وصفٌ للفعل والثاني للطبع."),

("ما مرادف «إجلال»؟ وما مرادف «يَحنَث»؟",
 "الإجلال: التعظيم والتبجيل. و«يحنث»: يُخلِف وعدَه وينقض يمينه",
 "والحِنْثُ في الأصل نقضُ اليمين، ومنه «التحنُّث» وهو التعبُّد لأن المتعبّد يتجنّب الحِنْث، فاللفظان من أصلٍ واحد والمعنى متقابل."),

("ما العلاقة بين «ليث» و«ضرغام» و«أسد»؟",
 "ترادف",
 "لأنها ألفاظٌ مختلفة لمعنًى واحد، والترادفُ من أدلّة سعة العربية، وقد أنكره بعضُ اللغويين وزعم أن لكل لفظٍ ظلًّا دلاليًّا يخصّه."),

("ما العلاقة بين «حرب» و«سلام»؟",
 "تضادّ (طباق)",
 "لأن اللفظين متقابلان في المعنى، وإذا اجتمعا في الكلام سُمّي طباقًا، وهو من المحسّنات المعنوية لأنه يُبرز المعنى بضدّه."),
