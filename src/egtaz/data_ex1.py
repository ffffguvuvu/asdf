("متى يُبنى الفعل المضارع؟ وعلى أيّ شيء؟",
 "يُبنى على السكون مع نون النسوة، وعلى الفتح مع نون التوكيد المباشِرة",
 "لأن نون النسوة ضميرُ رفعٍ متّصل فأشبه الفعل بها الماضيَ المبنيّ، ونونُ التوكيد لمّا باشرته ركّبته معها تركيبًا فأوجبت البناء."),

("«النساءُ يرجون الخيرَ» و«الرجالُ يرجون» — ما الفرق في إعراب «يرجون»؟",
 "الأولى مبنية على السكون لاتصالها بنون النسوة، والثانية مرفوعة بثبوت النون من الأفعال الخمسة",
 "فالنون في الأولى ضميرٌ فاعل، وفي الثانية علامةُ إعراب، واللفظ واحدٌ والفرق في الواو: ضميرٌ في الثانية وحرفُ إشباع في الأولى."),

("«لم ... الكذبُ صاحبَه» — أيّهما الصواب: يفيد أم يفد؟ ولماذا؟",
 "يفدْ — فعل مضارع مجزوم بـ«لم» وعلامة جزمه السكون، وحُذفت الياء لالتقاء الساكنين",
 "فأصل الفعل «يفيد»، فلمّا جُزم سكنت الدال، والتقى ساكنان: الياءُ والدال، فحُذفت الياء تخلّصًا من التقاء الساكنين."),

("«يتوارى» — أعرب هذا الفعل إذا وقع مرفوعًا.",
 "فعل مضارع مرفوع وعلامة رفعه الضمة المقدَّرة على الألف منع من ظهورها التعذّر",
 "لأن آخره ألفٌ لازمة لا تقبل الحركة أصلًا، فتعذَّر ظهورُ الحركة عليها، وهذا هو الفرق بين التعذّر في المقصور والثقل في المنقوص."),

("ما الفرق بين الإعراب المقدَّر في الاسم المقصور والمنقوص؟",
 "المقصور تُقدَّر فيه الحركات الثلاث للتعذّر، والمنقوص تُقدَّر فيه الضمة والكسرة للثقل وتظهر الفتحة",
 "لأن الألف لا تقبل حركةً بحال فتعذَّر، والياء تقبلها لكن الضمة والكسرة عليها ثقيلتان، والفتحة خفيفة فظهرت."),

("كيف يُجزم فعل الشرط وجوابه؟ اذكر الحالات الثلاث.",
 "بالسكون إن كان صحيح الآخر، وبحذف حرف العلة إن كان معتلّه، وبحذف النون إن كان من الأفعال الخمسة",
 "لأن الجزم في الأصل إسكانٌ، فإذا تعذّر الإسكان لعلّةٍ في الآخر نابت عنه علامةٌ أخرى: حذفُ الحرف أو حذفُ النون."),

# ===================== الإملاء والترقيم والأساليب =====================
("ما القاعدة الكلّية في رسم الهمزة المتطرفة؟",
 "تُكتب على ما يناسب حركة الحرف الذي قبلها لا حركتَها هي، فإن سكن ما قبلها كُتبت على السطر",
 "لأن الهمزة المتطرفة ساكنةٌ في التقدير أو ضعيفةُ الحركة، فاعتُبر ما قبلها، وهذا هو موضع الغلط الأكثر في هذا الباب."),

("لماذا كُتبت الهمزة على الواو في «تكافؤ» وعلى السطر في «عبء»؟",
 "لأن ما قبلها في «تكافؤ» مضموم، وما قبلها في «عبء» ساكن",
 "فالضمة تناسبها الواو، والساكنُ لا حركة له تُناسب حرفًا فتُكتب الهمزة مفردةً على السطر، وهذا جارٍ على القاعدة الكلّية نفسها."),

("ما علامة الترقيم المناسبة في «قال المعلم ... ما أجمل السماء ...»؟",
 "نقطتان رأسيتان بعد القول، وعلامة تعجّب في آخر الجملة",
 "لأن النقطتين توضعان قبل المقول وقبل التعداد والتفسير، وعلامةَ التعجّب توضع بعد أسلوب التعجّب القياسيّ «ما أفعله»."),

("«إيّاك نعبدُ وإيّاك نستعين» — ما الأسلوب البلاغي؟ وما سرّه؟",
 "أسلوب قصر بتقديم المفعول «إيّاك» على الفعل",
 "لأن تقديم ما حقُّه التأخير يفيد الاختصاص، فأفاد قصرَ العبادة والاستعانة على الله وحده، وهو قصرُ صفةٍ على موصوف."),

("«أيُضحَكُ مأثورٌ؟» — ما نوع الأسلوب وما غرضه؟",
 "استفهام غرضه التعجّب والاستنكار",
 "لأن المتكلم لا يطلب علمًا بما يجهل، وإنما يُنكر وقوع الأمر ويتعجّب منه، فخرج الاستفهام عن حقيقته إلى هذا الغرض البلاغي."),

("«صمٌّ بكمٌ عميٌ» — ما نوع التشبيه؟ ولماذا؟",
 "تشبيه بليغ، لحذف أداة التشبيه ووجه الشبه معًا",
 "فالتقدير «هم كالصمّ البكم العمي»، فلمّا حُذفت الأداة والوجه ادّعي أنّ المشبَّه هو عينُ المشبَّه به، فبلغ التشبيه أعلى مراتبه."),
