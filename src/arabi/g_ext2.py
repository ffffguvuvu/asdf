def gen_hamza_wq():
    for w, kind, why in HAMZA_WQ:
        mk("همزة كلمة «%s» همزة…" % w,
           "وصل" if kind == "وصل" else "قطع", ["وصل", "قطع"] * 2,
           "همزة «%s» همزة %s؛ لأنها %s. وهمزة الوصل تُنطق في الابتداء "
           "وتسقط في الدرج، وهمزة القطع تُنطق في الحالين."
           % (w, kind, why),
           "imla", "همزتا الوصل والقطع", 2, 3, rng=R)
        mk("ما سبب كون همزة «%s» همزة %s؟" % (w, kind), why,
           sorted({x[2] for x in HAMZA_WQ}),
           "همزة «%s» همزة %s؛ لأنها %s." % (w, kind, why),
           "imla", "تعليل همزتي الوصل والقطع", 3, 2, rng=R)
    pool_w = [w for w, k, _ in HAMZA_WQ if k == "وصل"]
    pool_q = [w for w, k, _ in HAMZA_WQ if k == "قطع"]
    for w, kind, why in HAMZA_WQ[:40]:
        other = pool_q if kind == "وصل" else pool_w
        opts = [w] + R.sample(other, 3)
        add("أيّ الكلمات الآتية همزتها همزة %s؟" % kind, opts, w,
            "«%s» همزتها همزة %s؛ لأنها %s. وبقية الكلمات همزتها همزة %s."
            % (w, kind, why, "قطع" if kind == "وصل" else "وصل"),
            "imla", "التمييز بين همزتي الوصل والقطع", 2, 3)


