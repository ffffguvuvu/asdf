def gen_rasm():
    for right, wrongs, why in RASM:
        add("أيّ الكلمات الآتية كُتبت كتابةً صحيحة؟", [right] + wrongs, right,
            "الصواب «%s»؛ لأن %s." % (right, why),
            "imla", "اختيار الرسم الصحيح", 2, 3)
        add("ما الصواب في رسم كلمة «%s»؟" % wrongs[0], [right] + wrongs,
            right, "الصواب «%s»؛ لأن %s." % (right, why),
            "imla", "تصويب الرسم الإملائي", 2, 3)
        mk("ما سبب كتابة «%s» على هذه الصورة؟" % right, why,
           [w for _, _, w in RASM],
           "«%s» كُتبت هكذا؛ لأن %s." % (right, why),
           "imla", "تعليل الرسم الإملائي", 3, 2, rng=R)


def gen_majhul():
    pool = [m[1] for m in MAJHUL]
    for act, pas, why in MAJHUL:
        mk("ابنِ الفعل للمجهول في قولنا: «%s»." % act, pas, pool,
           "«%s» ⇐ «%s»؛ لأنه %s." % (act, pas, why),
           "sarf", "البناء للمجهول", 3, 3, rng=R)
        parts = pas.split()
        if len(parts) < 2:
            continue
        nf = parts[1]
        mk("ما نائب الفاعل في قولنا: «%s»؟" % pas, nf,
           [x.split()[1] for x in pool if len(x.split()) > 1],
           "نائب الفاعل هو «%s»؛ فقد حُذف الفاعل وناب عنه المفعول به "
           "فأخذ حكمه في الرفع. و%s." % (nf, why),
           "sarf", "نائب الفاعل", 3, 2, rng=R)
    mads = [t[0] for t in TASRIF]
    mods = [t[1] for t in TASRIF]
    amrs = [t[2] for t in TASRIF]
    for mad, mod, amr in TASRIF:
        mk("ما مضارع الفعل «%s»؟" % mad, mod, mods,
           "مضارع «%s» هو «%s»، وأمره «%s». ويُبنى المضارع من الماضي "
           "بزيادة أحد حروف «أنيت» في أوله." % (mad, mod, amr),
           "sarf", "تصريف الفعل", 2, 3, rng=R)
        mk("ما الأمر من الفعل «%s»؟" % mad, amr, amrs,
           "الأمر من «%s» هو «%s»؛ ويُبنى من المضارع بحذف حرف المضارعة "
           "والجزم." % (mad, amr), "sarf", "تصريف الفعل", 2, 3, rng=R)
        mk("ما ماضي الفعل «%s»؟" % mod, mad, mads,
           "ماضي «%s» هو «%s»، وأمره «%s». والماضي مبنيّ دائمًا، "
           "والأمر مبنيّ على ما يُجزم به مضارعه." % (mod, mad, amr),
           "sarf", "تصريف الفعل", 2, 2, rng=R)


def gen_aghrad():
    defs = [a[1] for a in AGHRAD_SHI3R]
    names = [a[0] for a in AGHRAD_SHI3R]
    for name, define, who in AGHRAD_SHI3R:
        mk("ما المقصود بغرض «%s» في الشعر؟" % name, define, defs,
           "«%s»: %s. %s." % (name, define, who),
           "adab", "الأغراض الشعرية", 2, 3, rng=R)
        mk("الغرض الشعري الذي يقوم على «%s» هو…" % define, name, names,
           "هو «%s». %s." % (name, who), "adab", "الأغراض الشعرية",
           2, 2, rng=R)
    kh = [a[1] for a in ASUR]
    nm = [a[0] for a in ASUR]
    for name, khas in ASUR:
        mk("ما أبرز خصائص الأدب في «%s»؟" % name, khas, kh,
           "من أبرز خصائص الأدب في %s: %s." % (name, khas),
           "adab", "خصائص العصور الأدبية", 2, 3, rng=R)
        mk("العصر الذي من خصائصه «%s» هو…" % khas, name, nm,
           "هذه خصائص الأدب في «%s»: %s." % (name, khas),
           "adab", "خصائص العصور الأدبية", 3, 2, rng=R)


