           "وزن «%s» هو «%s». والميزان الصرفي يُقابل الحروف الأصلية بـ«ف ع ل» "
           "ويذكر الزوائد بلفظها في موضعها، ويُضبط بحركات الموزون، "
           "فإن حُذف من الكلمة حرف حُذف ما يقابله من الميزان." % (w, z),
