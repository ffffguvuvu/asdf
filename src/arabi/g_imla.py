def gen_wasl_qat():
    allw = HAMZA_W + HAMZA_Q
    for w, kind, why in allw:
        mk("همزة كلمة «%s»…" % w, "همزة %s" % kind,
           ["همزة وصل", "همزة قطع", "همزة متوسطة", "همزة متطرفة",
            "ألف لينة", "همزة ممدودة"],
           "همزة «%s» همزة %s؛ %s. والضابط: همزة الوصل تُنطق في أول الكلام "
           "وتسقط في وصله، ومواضعها: «ال» التعريف، والأسماء العشرة المسموعة، "
           "وأمر الثلاثي، وماضي وأمر ومصدر الخماسي والسداسي. "
           "وما عدا ذلك همزة قطع." % (w, kind, why),
           B, "همزة الوصل والقطع", 1 if kind == "قطع" else 2, 2, rng=R)
    for w, kind, why in allw[:18]:
        mk("لماذا كانت همزة «%s» همزة %s؟" % (w, kind), why,
           [x for _, _, x in allw],
           "همزة «%s» همزة %s لأنها %s." % (w, kind, why),
           B, "همزة الوصل والقطع", 2, 1, rng=R)


