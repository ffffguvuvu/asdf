_H = {"r": "مرفوع", "n": "منصوب", "g": "مجزوم"}


def gen_fi3l_erab():
    rows = []
    for row in VERBS_M:
        for ada, case, tpl, why in ADAWAT:
            w = row[_I[case]]
            mark = row[_M[case]]
            if case == "r" and row[6] == "من الأفعال الخمسة":
                sent = tpl.replace("الطالبُ", "الطلابُ") % w
            else:
                sent = tpl % w
            full = "فعل مضارع %s وعلامة %sه %s" % (
                _H[case], {"r": "رفع", "n": "نصب", "g": "جزم"}[case], mark)
            rows.append((sent, w, full, mark, why, row[6], ada, _H[case]))
