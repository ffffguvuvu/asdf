def gen_bina():
    kinds = sorted({k for _, k, _ in BINA})
    for w, kind, why in BINA:
        tail = ("والمبنيّ ما لزم آخره حالة واحدة، والمعرب ما تغيّر "
                "آخره بتغيّر موقعه من الجملة.")
        mk("كلمة «%s» من حيث البناء والإعراب…" % w, kind, kinds,
           "«%s» %s؛ لأنه %s. %s" % (w, kind, why, tail),
           B, "المبني والمعرب", 2, 3, rng=R)
        mk("ما سبب كون «%s» %s؟" % (w, kind), why,
           sorted({x[2] for x in BINA}),
           "«%s» %s؛ لأنه %s. %s" % (w, kind, why, tail),
           B, "تعليل البناء والإعراب", 3, 2, rng=R)


