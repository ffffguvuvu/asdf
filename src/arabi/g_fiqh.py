def gen_makharij():
    for hrf, mkhr in MAKHARIJ:
        mk("ما مخرج %s؟" % hrf, mkhr, [m for _, m in MAKHARIJ],
           "مخرج %s هو: %s. والمخارج العامّة خمسة: الجوف والحلق واللسان "
           "والشفتان والخيشوم." % (hrf, mkhr),
           B, "مخارج الأصوات", 3, 2, rng=R)
        mk("الحروف التي مخرجها «%s» هي…" % mkhr, hrf,
           [h for h, _ in MAKHARIJ],
           "الحروف الخارجة من «%s» هي: %s." % (mkhr, hrf),
           B, "مخارج الأصوات", 3, 1, rng=R)


def gen_sifat():
    for name, define in SIFAT:
        mk("ما المقصود بصفة «%s»؟" % name, define, [d for _, d in SIFAT],
           "«%s»: %s." % (name, define), B, "صفات الأصوات", 3, 2, rng=R)
        mk("الصفة التي تعريفها «%s» هي…" % define, name,
           [n for n, _ in SIFAT],
           "هي صفة «%s»." % name, B, "صفات الأصوات", 3, 1, rng=R)


