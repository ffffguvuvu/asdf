def gen_alqab():
    for lab, who, note in ALQAB:
        mk("«%s» لقبٌ للأديب…" % lab, who, [w for _, w, _ in ALQAB],
           "«%s» لقب %s؛ %s." % (lab, who, note),
           B, "ألقاب الأدباء", 2, 2, rng=R)
    for lab, who, note in ALQAB[:25]:
        mk("بماذا لُقّب «%s»؟" % who, lab, [l for l, _, _ in ALQAB],
           "لُقّب %s بـ«%s»؛ %s." % (who, lab, note),
           B, "ألقاب الأدباء", 2, 1, rng=R)


def gen_books():
    authors = [a for _, a, _ in BOOKS]
    titles = [t for t, _, _ in BOOKS]
    for title, author, note in BOOKS:
        mk("مؤلّف كتاب «%s» هو…" % title, author, authors,
           "«%s» من تأليف %s؛ %s." % (title, author, note),
           B, "الكتب ومؤلفوها", 2, 2, rng=R)
    for title, author, note in BOOKS[:30]:
        mk("مِن مؤلفات %s كتاب…" % author, title, titles,
           "من مؤلفات %s كتاب «%s»؛ %s." % (author, title, note),
           B, "الكتب ومؤلفوها", 2, 1, rng=R)


def gen_eras():
    for who, era in ERAS:
        mk("الشاعر «%s» من شعراء…" % who, era, ERA_POOL,
           "«%s» من شعراء %s. والعصور الأدبية: الجاهلي، وصدر الإسلام، "
           "والأموي، والعباسي، والأندلسي، والمملوكي والعثماني، والحديث."
           % (who, era), B, "العصور الأدبية", 2, 2, rng=R)
    for who, sch in SCHOOLS:
        mk("الشاعر «%s» ينتمي إلى…" % who, sch, SCHOOL_POOL,
           "«%s» من أعلام %s." % (who, sch),
           B, "المدارس الشعرية", 2, 2, rng=R)
    for sch in SCHOOL_POOL:
        members = [w for w, s in SCHOOLS if s == sch]
        others = [w for w, s in SCHOOLS if s != sch]
        if len(others) >= 3:
            mk("أيّ الشعراء الآتية أسماؤهم ينتمي إلى «%s»؟" % sch,
               members[0], [members[0]] + others,
               "«%s» من أعلام %s، ومن أبرز أعلامها أيضًا: %s."
               % (members[0], sch, "، ".join(members[1:4]) or members[0]),
               B, "المدارس الشعرية", 2, 1, rng=R)


