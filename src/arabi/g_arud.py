def gen_buhur():
    names = [n for n, _, _ in BUHUR]
    tafs = [t for _, t, _ in BUHUR]
    for name, taf, key in BUHUR:
        mk("ما تفعيلات بحر «%s» في الشطر الواحد؟" % name, taf, tafs,
           "تفعيلات «%s»: %s. ومفتاحه: %s" % (name, taf, key),
           B, "البحور وتفعيلاتها", 2, 3, rng=R)
        mk("التفعيلات «%s» هي تفعيلات بحر…" % taf, name, names,
           "هذه تفعيلات بحر «%s»، ومفتاحه: %s" % (name, key),
           B, "البحور وتفعيلاتها", 2, 2, rng=R)
        mk("المفتاح «%s» دالٌّ على بحر…" % key.split("—")[0].strip(), name,
           names, "هذا مفتاح بحر «%s»، وتفعيلاته: %s" % (name, taf),
           B, "مفاتيح البحور", 2, 2, rng=R)
    for line, bhr in ABYAT:
        mk("من أيّ بحر قول الشاعر: «%s»؟" % line, bhr, names,
           "هذا الشطر من بحر «%s». ويُعرف البحر بتقطيع الشطر عروضيًّا "
           "ومطابقته بتفعيلات البحور." % bhr,
           B, "تحديد البحر", 3, 3, rng=R)


