def gen_udaba():
    eras = sorted({u[1] for u in UDABA})
    descs = [u[2] for u in UDABA]
    works = [u[3] for u in UDABA]
    names = [u[0] for u in UDABA]
    for name, era, desc, work in UDABA:
        mk("إلى أيّ عصر ينتمي «%s»؟" % name, era, eras * 2,
           "«%s» من أعلام العصر %s؛ وهو %s." % (name, era, desc),
           "adab", "العصور الأدبية وأعلامها", 2, 3, rng=R)
        mk("بماذا اشتهر «%s»؟" % name, desc, descs,
           "«%s» %s، ومن آثاره: %s." % (name, desc, work),
           "adab", "أعلام الأدب وألقابهم", 2, 3, rng=R)
        mk("ما أشهر آثار «%s»؟" % name, work, works,
           "من أشهر آثار «%s» (%s): %s." % (name, desc, work),
           "adab", "الآثار الأدبية وأصحابها", 2, 3, rng=R)
        mk("صاحب «%s» هو…" % work, name, names,
           "«%s» لـ«%s»، وهو %s من أعلام العصر %s."
           % (work, name, desc, era),
           "adab", "الآثار الأدبية وأصحابها", 2, 2, rng=R)


