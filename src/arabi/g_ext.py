def gen_erab():
    rows = []
    for ra, na, ja, mr, mn, mj, kind, g, a, d in NOUNS:
        forms, marks = (ra, na, ja), (mr, mn, mj)
        for role, case, build, why, allow in ROLES:
            if d == "i" and "I" not in allow:
                continue
            if allow == "A" and a != "a":
                continue
            w = forms[_IDX[case]]
            sent = build(w, g, a)
            full = "%s %s وعلامة %sه %s" % (
                role, _HAL[case], _MSD[case], marks[_IDX[case]])
            rows.append((sent, w, role, _HAL[case], marks[_IDX[case]],
                         full, kind, why))
    pool_full = sorted({r[5] for r in rows})
    pool_role = sorted({"%s %s" % (r[2], r[3]) for r in rows})
    pool_mark = sorted({r[4] for r in rows})
    pool_kind = sorted({r[6] for r in rows})
    for sent, w, role, hal, mark, full, kind, why in rows:
        mk("أعرب ما تحته خطّ: «%s» في قولنا: %s." % (w, sent), full, pool_full,
           "«%s» %s؛ لأن %s. وهو %s، فلذلك كانت علامة إعرابه %s."
           % (w, full, why, kind, mark),
           "nahw", "الإعراب التطبيقي", 2, 3, rng=R)
        mk("ما الموقع الإعرابي لكلمة «%s» في قولنا: %s؟" % (w, sent),
           "%s %s" % (role, hal), pool_role,
           "«%s» %s؛ لأن %s." % (w, full, why),
           "nahw", "تحديد الموقع الإعرابي", 2, 3, rng=R)
        mk("ما علامة إعراب «%s» في قولنا: %s؟" % (w, sent), mark, pool_mark,
           "«%s» %s؛ لأنه %s." % (w, full, kind),
           "nahw", "علامات الإعراب", 2, 3, rng=R)
        mk("كلمة «%s» في قولنا: %s، نوعها…" % (w, sent), kind, pool_kind,
           "«%s» %s، ولذلك أُعرب بـ%s، وهو في هذا التركيب %s."
           % (w, kind, mark, full),
           "nahw", "أنواع الأسماء المعربة", 2, 2, rng=R)


