# توزيع الإجابات الصحيحة على الحروف الأربعة (بدل تكرار حرفين فقط)
_c = [0, 0, 0, 0]
EXAM = []
for _prompt, _opts, _ans, _why in EXAM_RAW:
    _t = min(range(4), key=lambda k: (_c[k], k))
    _shift = (_t - _ans) % 4
    if _shift:
        _q = Q(_prompt, list(_opts), _ans, [_why])
        reorder(_q, [(i - _shift) % 4 for i in range(4)])
        _opts, _ans, _why = _q["options"], _q["answer"], _q["steps"][0]
    _c[_ans] += 1
    EXAM.append((_prompt, list(_opts), _ans, _why))


