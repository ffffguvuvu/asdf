def numbox(rows, qpos=None, color="#38bdf8"):
    """مربع ٢×٢ أو شبكة أرقام."""
    inner = ""
    n = len(rows)
    m = len(rows[0])
    w = 72 / m
    h = 72 / n
    for r in range(n):
        for c in range(m):
            x = 14 + c * w
            y = 14 + r * h
            isq = (qpos == (r, c))
            inner += f'<rect x="{x:.1f}" y="{y:.1f}" width="{w:.1f}" height="{h:.1f}" fill="{"#fff7ed" if isq else "#f0f9ff"}" stroke="{color}" stroke-width="2.5"/>'
            v = "؟" if isq else ar(rows[r][c])
            inner += text(v, x + w / 2, y + h / 2 + 1, 19, RED if isq else INK, "800")
    return inner


