def lchips(values, color="#7c3aed"):
    html = f'<div class="series" dir="ltr" style="--chip:{color}">'
    for v in values:
        html += '<span class="chip q">؟</span>' if v is None else f'<span class="chip">{v}</span>'
    html += "</div>"
    return html


