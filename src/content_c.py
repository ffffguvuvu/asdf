_AR = "٠١٢٣٤٥٦٧٨٩"


def ar(x):
    """تحويل الأرقام إلى الأرقام العربية الهندية المستخدمة في الاختبارات."""
    s = str(x)
    out = ""
    for ch in s:
        if ch.isdigit():
            out += _AR[int(ch)]
        elif ch == ".":
            out += "٫"
        else:
            out += ch
    return out


def chips(values, color="#2563eb"):
    """صف من بطاقات الأرقام/الحروف، وعلامة ؟ لكل قيمة تساوي None."""
    html = f'<div class="series" dir="ltr" style="--chip:{color}">'
    for v in values:
        if v is None:
            html += '<span class="chip q">؟</span>'
        else:
            html += f'<span class="chip">{ar(v)}</span>'
    html += "</div>"
    return html


def nums(*vals):
    return [ar(v) for v in vals]


