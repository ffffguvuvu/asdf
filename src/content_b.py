def _merge_part(parts, color=BLUE):
    m = {
        "v": line(50, 16, 50, 84, color, 6),
        "h": line(16, 50, 84, 50, color, 6),
        "d1": line(20, 20, 80, 80, color, 6),
        "d2": line(80, 20, 20, 80, color, 6),
        "o": circle(50, 50, 20, "none", color, 5),
        "sq": rect(26, 26, 48, 48, "none", color, 5),
        "tri": f'<polygon points="50,24 78,74 22,74" fill="none" stroke="{color}" stroke-width="5" stroke-linejoin="round"/>',
    }
    return "".join(m[p] for p in parts)


