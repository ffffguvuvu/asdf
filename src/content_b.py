def _piece_square(marks=(("X", "right"),), color="#bfdbfe"):
    """قطعة مربعة، الحافة الملوّنة بالأحمر هي حافة اللصق ومكتوب عليها الحرف."""
    x0, y0, w = 26, 32, 44
    inner = rect(x0, y0, w, w, color, INK, 3)
    for label, edge in marks:
        if edge == "right":
            inner += line(x0 + w, y0, x0 + w, y0 + w, RED, 4) + text(label, x0 + w + 11, y0 + w / 2, 18, RED, "800")
        elif edge == "top":
            inner += line(x0, y0, x0 + w, y0, RED, 4) + text(label, x0 + w / 2, y0 - 12, 18, RED, "800")
        elif edge == "left":
            inner += line(x0, y0, x0, y0 + w, RED, 4) + text(label, x0 - 11, y0 + w / 2, 18, RED, "800")
        else:
            inner += line(x0, y0 + w, x0 + w, y0 + w, RED, 4) + text(label, x0 + w / 2, y0 + w + 12, 18, RED, "800")
    return inner


def _piece_tri(label="X", color="#fecaca", rotate=0):
    """قطعة مثلثة، قاعدتها الحمراء هي حافة اللصق (تدور مع الشكل والحرف يبقى معتدلًا)."""
    tri = (f'<polygon points="50,26 76,66 24,66" fill="{color}" stroke="{INK}" stroke-width="3" stroke-linejoin="round"/>'
           + line(24, 66, 76, 66, RED, 4))
    inner = transform(tri, rotate=rotate)
    pos = {0: (50, 80), 90: (16, 50), 180: (50, 20), 270: (84, 50)}[rotate % 360]
    return inner + text(label, pos[0], pos[1], 18, RED, "800")


