def vox_fig(vox, rx=0, ry=0, rz=0, u=12):
    return bfig(voxels(vox, rx=rx, ry=ry, rz=rz, u=u))


def topview(cells, n=3, color="#93c5fd"):
    """منظر علوي: شبكة n×n مع تظليل الخانات المشغولة."""
    s = 70 / n
    inner = ""
    for r in range(n):
        for c in range(n):
            f = color if (c, r) in cells else WHITE
            inner += f'<rect x="{15 + c * s:.1f}" y="{15 + r * s:.1f}" width="{s:.1f}" height="{s:.1f}" fill="{f}" stroke="{INK}" stroke-width="2"/>'
    return inner


