def _dots_cluster(n, color=BLUE):
    if n == 1:
        pos = [(50, 50)]
    elif n == 2:
        pos = [(35, 50), (65, 50)]
    elif n == 3:
        pos = [(50, 32), (34, 64), (66, 64)]
    elif n == 4:
        pos = [(34, 34), (66, 34), (34, 66), (66, 66)]
    elif n == 5:
        pos = [(32, 32), (68, 32), (50, 50), (32, 68), (68, 68)]
    elif n == 6:
        pos = [(32, 30), (68, 30), (32, 50), (68, 50), (32, 70), (68, 70)]
    elif n == 7:
        pos = [(32, 30), (68, 30), (32, 50), (68, 50), (32, 70), (68, 70), (50, 50)]
    elif n == 8:
        pos = [(30, 30), (50, 28), (70, 30), (30, 50), (70, 50), (30, 70), (50, 72), (70, 70)]
    else:
        pos = [(30, 30), (50, 30), (70, 30), (30, 50), (50, 50), (70, 50), (30, 70), (50, 70), (70, 70)]
    return "".join(dot(x, y, 8, color) for x, y in pos)


