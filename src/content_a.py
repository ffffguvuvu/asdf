def _dot_in_box(pos, color=RED):
    y = {"top": 30, "mid": 50, "bot": 70}[pos]
    return rect(16, 16, 68, 68, "#eff6ff", BLUE, 3.5, 6) + dot(50, y, 9, color)


def _poly_dots(n, k, fill=WHITE):
    inner = polygon(n, 32, fill="#ecfeff", stroke=TEAL, sw=4)
    for i, (x, y) in enumerate(poly_pts(k, 15, start=-90)):
        inner += dot(x, y, 5.5, INK)
    return inner


def _zig_dot(n, pos):
    x = {"r": 78, "c": 50, "l": 22}[pos]
    return zigzag(n, PURPLE, 5, 26, 62) + dot(x, 84, 6, RED)


def _lmotif(color=AMBER):
    """شكل حرف L غير متماثل حتى يظهر أثر التدوير بوضوح."""
    return (
        f'<polygon points="30,22 52,22 52,56 74,56 74,78 30,78" fill="{color}" '
        f'stroke="{INK}" stroke-width="3" stroke-linejoin="round"/>' + dot(41, 32, 5, INK)
    )


def _tri_dot(n_sides, filled):
    f = INK if filled else WHITE
    return polygon(n_sides, 30, fill="#fdf4ff", stroke=PINK, sw=4) + dot(50, 50, 9, f, INK, 2)


