# ============================================================ ١٥ الأعداد داخل الأشكال
def numshape_bank():
    """٦٠+ سؤالًا على الأرقام داخل الأشكال بقواعد متنوعة."""
    out, k = [], 0

    rules = [
        (lambda a, b, c: a + b + c, "مجموع الأرقام الثلاثة", "{a} + {b} + {c}"),
        (lambda a, b, c: a * b - c, "حاصل ضرب العلويين ناقص السفلي", "{a} × {b} − {c}"),
        (lambda a, b, c: a * b + c, "حاصل ضرب العلويين زائد السفلي", "{a} × {b} + {c}"),
        (lambda a, b, c: (a + b) * c, "مجموع الأولين مضروبًا في الثالث", "({a} + {b}) × {c}"),
        (lambda a, b, c: a * c - b, "الأول × الثالث − الثاني", "{a} × {c} − {b}"),
        (lambda a, b, c: (a + c) * 2 - b, "ضعف مجموع الطرفين ناقص الأوسط", "({a} + {c}) × ٢ − {b}"),
    ]
    sets = [((4, 6, 8), (3, 5, 3), (2, 7, 5)), ((5, 4, 6), (7, 2, 3), (6, 3, 4)),
            ((3, 8, 5), (6, 4, 7), (9, 2, 6)), ((2, 9, 4), (5, 6, 8), (7, 3, 9))]
    for rule, name, pat in rules:
        for trio in sets:
            (a1, b1, c1), (a2, b2, c2), (a3, b3, c3) = trio
            v1, v2, v3 = rule(a1, b1, c1), rule(a2, b2, c2), rule(a3, b3, c3)
            if min(v1, v2, v3) < 0:
                continue
            out.append(gq("ما الرقم الناقص في الشكل الثالث؟", v3,
                          [v3 + 1, v3 - 1, v3 + 2, a3 + b3 + c3, a3 * b3],
                          [f"ابحث عن قاعدة تربط أرقام البتلات بالمركز في الشكل الأول: "
                           f"{pat.format(a=ar(a1), b=ar(b1), c=ar(c1))} = {ar(v1)} ✔",
                           f"تأكّد بالشكل الثاني: {pat.format(a=ar(a2), b=ar(b2), c=ar(c2))} = {ar(v2)} ✔",
                           f"القاعدة = {name}.",
                           f"طبّقها على الثالث: {pat.format(a=ar(a3), b=ar(b3), c=ar(c3))} = {ar(v3)}."],
                          [fig(flower([a1, b1, c1], v1)), fig(flower([a2, b2, c2], v2)),
                           fig(flower([a3, b3, c3], None))], k=k,
                          tip="جرّب الجمع أولًا، فإن فشل فجرّب الضرب مع جمع أو طرح."))
            k += 1

    # مربعات ٢×٢
    for (a, b, c), rule, name in [((3, 4, 5), lambda a, b, c: a + b + c, "مجموع الثلاثة"),
                                  ((2, 6, 3), lambda a, b, c: a * b - c, "الأول × الثاني − الثالث"),
                                  ((5, 3, 2), lambda a, b, c: a * c + b, "الأول × الثالث + الثاني"),
                                  ((8, 2, 4), lambda a, b, c: a - b + c, "الأول − الثاني + الثالث"),
                                  ((7, 5, 6), lambda a, b, c: a + b - c, "مجموع الأولين − الثالث"),
                                  ((4, 9, 3), lambda a, b, c: (a + b) // c if (a + b) % c == 0 else a + b + c,
                                   "مجموع الأولين ÷ الثالث")]:
        for shift in (0, 1, 2):
            A, B, C = a + shift, b + shift, c + shift
            v = rule(A, B, C)
            out.append(gq("ما الرقم الناقص في المربع؟", v,
                          [v + 1, v - 1, v + 3, A + B + C, A * B],
                          [f"الخانات الثلاث المعلومة: {ar(A)} و{ar(B)} و{ar(C)}.",
                           f"القاعدة المستعملة في هذا النوع: {name}.",
                           f"الناتج = {ar(v)} ⇐ يوضع في الخانة الفارغة."],
                          [bfig(numbox([[A, B], [C, None]], qpos=(1, 1)))], k=k,
                          tip="في المربعات جرّب: المجموع، الفرق، الضرب، ثم الضرب مع الطرح."))
            k += 1

    # سلاسل الدوائر الثلاث
    for a, m, c in ((3, 2, 1), (4, 3, 2), (5, 2, 3), (2, 4, 1), (6, 2, 5), (7, 3, 4)):
        b = a * m + c
        d = b * m + c
        out.append(gq("ما الرقم الناقص في السلسلة؟", d,
                      [d + 1, d - 1, b + m, a * m],
                      [f"من الأولى إلى الثانية: {ar(a)} × {ar(m)} + {ar(c)} = {ar(b)}.",
                       "نفس العملية تنتقل من دائرة إلى التي تليها.",
                       f"إذن: {ar(b)} × {ar(m)} + {ar(c)} = {ar(d)}."],
                      [bfig(chain([a, b, None]))], k=k,
                      tip="السلسلة تعني عملية واحدة تتكرر، لا قاعدة جديدة لكل خطوة."))
        k += 1

    # شبكات ٣×٣ (العمود الثالث = مجموع/فرق العمودين)
    for base, op, name in ((2, "sum", "العمود الثالث = مجموع العمودين الأولين"),
                           (3, "diff", "العمود الثالث = فرق العمودين الأولين"),
                           (1, "prod", "العمود الثالث = حاصل ضرب العمودين الأولين")):
        for t in range(3):
            rows, ans = [], None
            for r in range(3):
                x = base + r + t
                y = base + 2 * r + 1 + t
                z = x + y if op == "sum" else (abs(x - y) if op == "diff" else x * y)
                rows.append([x, y, z if r < 2 else None])
                if r == 2:
                    ans = z
            out.append(gq("ما الرقم الناقص في الشبكة؟", ans,
                          [ans + 1, ans - 1, ans + 2, ans - 2],
                          [f"افحص الصف الأول: {ar(rows[0][0])} و{ar(rows[0][1])} والناتج {ar(rows[0][2])}.",
                           f"القاعدة: {name} (تحقّق منها في الصف الثاني أيضًا).",
                           f"الصف الثالث: {ar(rows[2][0])} و{ar(rows[2][1])} ⇐ الناقص = {ar(ans)}."],
                          [bfig(numbox(rows, qpos=(2, 2)))], k=k,
                          tip="افحص الصفوف أولًا، فإن فشلت فافحص الأعمدة ثم القطرين."))
            k += 1

    return out


# ======================================================================= ١٦ الميزان
def balance_bank():
    """٤٠ سؤال ميزان: قيمة شكل، أو عدد الوحدات المكافئة، أو ما يحقق التوازن."""
    out, k = [], 0

    # مثلثات = دوائر، والدائرة معلومة القيمة
    for t, c in ((2, 4), (2, 6), (3, 6), (2, 8), (3, 9), (4, 8), (2, 10), (3, 12)):
        for unit in (2, 3, 5):
            val = c * unit / t
            if val != int(val):
                continue
            val = int(val)
            out.append(gq(f"إذا كانت الدائرة = {ar(unit)} كجم، فما وزن المثلث؟", f"{ar(val)} كجم",
                          [f"{ar(val + 1)} كجم", f"{ar(val - 1)} كجم", f"{ar(val * 2)} كجم",
                           f"{ar(c * unit)} كجم"],
                          [f"الميزان متزن ⇐ {ar(t)} مثلث = {ar(c)} دائرة.",
                           f"قيمة الكفة اليمنى = {ar(c)} × {ar(unit)} = {ar(c * unit)} كجم.",
                           f"إذن {ar(t)} مثلث = {ar(c * unit)} كجم ⇐ المثلث الواحد = {ar(c * unit)} ÷ {ar(t)} = {ar(val)} كجم."],
                          [bfig(balance([TRI_S] * t, [CIR_S] * c))], k=k,
                          formatter=lambda x: x,
                          tip="لا تنسَ القسمة الأخيرة على عدد الأشكال في الكفة."))
            k += 1

    # ميزانان: تحويل كل الأشكال إلى وحدة واحدة
    for sq, tri in ((2, 3), (3, 2), (2, 4), (4, 3), (3, 5), (2, 5), (4, 2), (5, 3)):
        tot = sq + tri
        out.append(gq("كم دائرة تعادل (مربعًا + مثلثًا) معًا؟", f"{ar(tot)} دوائر",
                      [f"{ar(tot + 1)} دوائر", f"{ar(tot - 1)} دوائر", f"{ar(sq * tri)} دوائر",
                       f"{ar(tot + 2)} دوائر"],
                      [f"من الميزان الأول: المربع = {ar(sq)} دائرة.",
                       f"من الميزان الثاني: المثلث = {ar(tri)} دائرة.",
                       f"إذن مربع + مثلث = {ar(sq)} + {ar(tri)} = {ar(tot)} دوائر."],
                      [bfig(balance([SQ_S], [CIR_S] * sq)), bfig(balance([TRI_S], [CIR_S] * tri))],
                      k=k, formatter=lambda x: x,
                      tip="وحّد كل الأشكال في «عملة» واحدة (الدائرة) ثم اجمع."))
        k += 1

    # ما الذي يحقق التوازن (اختيارات مرسومة)
    from genlib import gqf, rotate_options
    for extra, label in ((CIR_S, "دائرة"), (TRI_S, "مثلث"), (SQ_S, "مربع"), (STAR_S, "نجمة")):
        for n in (1, 2):
            rest = [x for x in (CIR_S, TRI_S, SQ_S, STAR_S) if x != extra][:3]
            opts = [fig(extra)] + [fig(x) for x in rest]
            opts, ansi = rotate_options(opts, 0, k)
            out.append(gqf(f"ما الشكل الذي يجعل الميزان متزنًا؟", opts, ansi,
                           [f"الكفة اليمنى: {label} + {'نجمة' if n == 1 else 'نجمتان'}.",
                            f"الكفة اليسرى: {'نجمة' if n == 1 else 'نجمتان'} + الشكل المجهول.",
                            "احذف المتكرر من الكفتين (الاختزال) يتبقى: المجهول = " + label + ".",
                            "إذن الشكل المطلوب هو " + label + "."],
                           [bfig(balance([STAR_S] * n + [QM.replace('class="fig"', 'class="x"')
                                                         if False else CIR_S * 0 or
                                                         '<text x="50" y="62" font-size="46" fill="#dc2626" '
                                                         'text-anchor="middle" font-weight="800">؟</text>'],
                                         [STAR_S] * n + [extra]))],
                           tip="الاختزال: احذف الأشكال المشتركة من الكفتين قبل الحساب."))
            k += 1

    # ترتيب الأوزان
    for a, b, c in (("المربع", "المثلث", "الدائرة"), ("النجمة", "المربع", "المثلث"),
                    ("المعيّن", "الدائرة", "النجمة")):
        for ask in ("أثقل", "أخف"):
            ans = a if ask == "أثقل" else c
            kana = "كانت" if a in ("النجمة", "الدائرة") else "كان"
            out.append(gq(f"إذا {kana} {a} أثقل من {b}، و{b} أثقل من {c}، فأيّها الأ{ask[1:]}؟", ans,
                          [b, c if ask == "أثقل" else a, f"{b} و{c} متساويان"],
                          [f"رتّب من الأثقل إلى الأخف: {a} > {b} > {c}.",
                           "الترتيب متعدٍّ: ما دام الأول أثقل من الثاني والثاني أثقل من الثالث، فالترتيب كامل بلا تناقض.",
                           f"إذن الأ{ask[1:]} هو {ans}."],
                          None, k=k, formatter=lambda x: x,
                          tip="ارسم سهمًا واحدًا من الأثقل إلى الأخف ورتّب عليه الأشكال."))
            k += 1

    return out


