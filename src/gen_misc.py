def verbal_bank():
    """٤٠ سؤالًا: تناظر لفظي + أمثال شعبية بشرح العلاقة."""
    out, k = [], 0
    for first, second, opts, ans, why in VERBAL:
        pool = opts[1:] + [opts[0]]
        out.append(gq(f"أكمل التناظر اللفظي:  {first}  ::  {second}", opts[ans], pool,
                      [f"حدّد العلاقة في الطرف الأول «{first}» بدقة.",
                       why,
                       f"طبّق نفس العلاقة على الطرف الثاني ⇐ «{opts[ans]}»."],
                      None, k=k, formatter=lambda x: x,
                      tip="صُغ العلاقة في جملة قصيرة قبل النظر إلى الاختيارات."))
        k += 1
    for prompt, opts, ans, why in PROVERBS:
        out.append(gq(prompt, opts[ans], opts[1:] + [opts[0]],
                      ["المثل لا يُفهم حرفيًا، بل بالمعنى المجازي.",
                       why,
                       f"إذن المعنى الصحيح: {opts[ans]}."],
                      None, k=k, formatter=lambda x: x,
                      tip="ابحث عن المعنى العام لا عن ترجمة الكلمات."))
        k += 1
    return out


# ======================================================= ١٩ الاستدلال المنطقي
WORDS = ["CAT", "DOG", "SUN", "BOX", "PEN", "CUP", "MAP", "BED", "FAN", "JAR",
         "KEY", "LOG", "NET", "OWL", "PIG", "RAT"]


def logic_bank():
    """٦٠+ سؤال استدلال: ترميز، ساعات، قرابة، أيام، أعمار، اتجاهات، قياس منطقي."""
    out, k = [], 0

    def shift(w, s):
        return "".join(en_letter((ord(c) - 64 + s - 1) % 26 + 1) for c in w)

    # ١) الترميز بالإزاحة
    for s in (1, 2, 3, -1):
        for i in range(4):
            a, b = WORDS[i], WORDS[i + 4]
            ca, cb = shift(a, s), shift(b, s)
            sgn = f"+{ar(s)}" if s > 0 else f"−{ar(-s)}"
            out.append(gq(f"إذا كان {a} = {ca} فإن {b} = ؟", cb,
                          [shift(b, s + 1), shift(b, s - 1), shift(b, -s), shift(b, s + 2)],
                          [f"قارن حرفًا بحرف: {a[0]} ← {ca[0]} ومعناها إزاحة {sgn} في ترتيب الأبجدية.",
                           f"تحقّق من الحرفين الباقيين: {a[1]} ← {ca[1]} و{a[2]} ← {ca[2]} ✔",
                           f"طبّق نفس الإزاحة على {b}: " + "، ".join(f"{x} ← {y}" for x, y in zip(b, cb)) + f" ⇐ {cb}."],
                          None, k=k, formatter=lambda x: x,
                          tip="اكتب ترتيب الحروف A=1 … Z=26 ثم اجمع أو اطرح."))
            k += 1

    # ٢) زوايا عقارب الساعة
    for h, m in ((3, 0), (6, 0), (9, 0), (4, 0), (2, 0), (5, 0), (3, 30), (9, 30),
                 (12, 30), (1, 30), (4, 30), (7, 30)):
        ang = abs(30 * (h % 12) - 5.5 * m)
        ang = min(ang, 360 - ang)
        txt = f"{ar(h)}:{'٠٠' if m == 0 else ar(m)}"
        out.append(gq(f"ما الزاوية بين عقربي الساعة في تمام {txt}؟", f"{fmt(ang)}°",
                      [f"{fmt(ang + 15)}°", f"{fmt(abs(ang - 15))}°", f"{fmt(ang + 30)}°", f"{fmt(ang / 2)}°"],
                      ["الساعة ٣٦٠° مقسّمة على ١٢ ⇒ كل ساعة = ٣٠°، وعقرب الدقائق يتحرك ٦° في الدقيقة.",
                       f"موضع عقرب الساعات = {ar(h % 12)} × ٣٠ + {ar(m)} × ٠٫٥ = {fmt((h % 12) * 30 + m * 0.5)}°.",
                       f"موضع عقرب الدقائق = {ar(m)} × ٦ = {fmt(m * 6)}°.",
                       f"الفرق = {fmt(ang)}°."],
                      None, k=k, formatter=lambda x: x,
                      tip="القانون المختصر: |٣٠ × الساعات − ٥٫٥ × الدقائق|."))
        k += 1

    # ٣) صلة القرابة
    rel = [("أخو والد سالم", "عمّه", ["خاله", "جدّه", "ابن عمه"]),
           ("أخت والدة سالم", "خالته", ["عمّته", "جدّته", "أختها"]),
           ("ابن أخت أمي", "ابن خالتي", ["ابن عمتي", "أخي", "ابن خالي"]),
           ("أبو زوجة الرجل", "حَموه", ["عمّه", "خاله", "صهره"]),
           ("ابنة ابني", "حفيدتي", ["أختي", "ابنتي", "ابنة أخي"]),
           ("أخو زوجتي", "صهري (أخو الزوجة)", ["عمّي", "ابن خالي", "جدّي"]),
           ("ابن عمّ أبي", "ابن عمّ أبي (قريب من جهة الأب)", ["خالي", "أخي", "عمّي"]),
           ("أمّ أمّ الولد", "جدّته لأمه", ["جدّته لأبيه", "خالته", "عمّته"])]
    for q, ans, dis in rel:
        out.append(gq(f"حدّد صلة القرابة الصحيحة: {q} هو/هي بالنسبة للمتكلّم:", ans, dis,
                      ["ارسم شجرة العائلة في ذهنك وابدأ من الشخص المذكور.",
                       "تذكّر: أخو الأب = العم، وأخت الأب = العمّة، وأخو الأم = الخال، وأخت الأم = الخالة.",
                       f"بالتطبيق: {q} = {ans}."],
                      None, k=k, formatter=lambda x: x,
                      tip="ارسم مربعات صغيرة للأب والأم وتدرّج منها؛ أسرع من التخيّل."))
        k += 1

    # ٤) حساب الأيام
    days = ["السبت", "الأحد", "الاثنين", "الثلاثاء", "الأربعاء", "الخميس", "الجمعة"]
    for start in range(7):
        for n in (10, 25, 45, 100):
            ans = days[(start + n) % 7]
            out.append(gq(f"إذا كان اليوم {days[start]}، فما اليوم بعد {ar(n)} يومًا؟", ans,
                          [days[(start + n + 1) % 7], days[(start + n - 1) % 7], days[(start + n + 2) % 7]],
                          [f"الأسبوع ٧ أيام ⇒ اقسم {ar(n)} على ٧.",
                           f"{ar(n)} ÷ ٧ = {ar(n // 7)} وباقي {ar(n % 7)}.",
                           f"تقدّم {ar(n % 7)} أيام من {days[start]} ⇐ {ans}."],
                          None, k=k, formatter=lambda x: x,
                          tip="الباقي من القسمة على ٧ هو كل ما يهم."))
            k += 1
            if len(out) % 4 == 0:
                break

    # ٥) الأعمار
    for s, r in ((21, 2), (24, 3), (36, 3), (30, 4), (45, 2), (40, 4)):
        young = s // (r + 1)
        old = s - young
        out.append(gq(f"عمر الأب {ar(r)} أضعاف عمر ابنه، ومجموع عمريهما {ar(s)} سنة. فما عمر الابن؟",
                      f"{ar(young)} سنة",
                      [f"{ar(young + 1)} سنة", f"{ar(old)} سنة", f"{ar(young * 2)} سنة"],
                      [f"افرض عمر الابن = س ⇒ عمر الأب = {ar(r)}س.",
                       f"المجموع: س + {ar(r)}س = {ar(r + 1)}س = {ar(s)}.",
                       f"س = {ar(s)} ÷ {ar(r + 1)} = {ar(young)} سنة (وعمر الأب {ar(old)})."],
                      None, k=k, formatter=lambda x: x,
                      tip="سمِّ المجهول «س» وحوّل الكلام إلى معادلة."))
        k += 1

    # ٦) الاتجاهات
    dirs = ["الشمال", "الشرق", "الجنوب", "الغرب"]
    for start in range(4):
        for turns, desc in (([1, 1], "انعطف يمينًا مرتين"), ([1, 1, 1], "انعطف يمينًا ثلاث مرات"),
                            ([-1, -1], "انعطف يسارًا مرتين"), ([1, -1, 1], "يمين ثم يسار ثم يمين")):
            cur = start
            for t in turns:
                cur = (cur + t) % 4
            out.append(gq(f"شخص يسير نحو {dirs[start]} ثم {desc}. في أي اتجاه يسير الآن؟", dirs[cur],
                          [dirs[(cur + 1) % 4], dirs[(cur + 2) % 4], dirs[(cur + 3) % 4]],
                          ["ارسم صليبًا: شمال أعلى، جنوب أسفل، شرق يمين، غرب يسار.",
                           "كل انعطاف يمين = ربع دورة مع عقارب الساعة، واليسار عكسها.",
                           f"بعد تنفيذ الانعطافات من {dirs[start]} نصل إلى {dirs[cur]}."],
                          None, k=k, formatter=lambda x: x,
                          tip="نفّذ الدوران بإصبعك على الورقة؛ أدق من التخيّل."))
            k += 1

    # ٧) القياس المنطقي
    syl = [("كل المعلمين موظفون، وبعض الموظفين أطباء.", "كل المعلمين موظفون",
            ["كل الأطباء معلمون", "بعض المعلمين أطباء", "لا طبيب موظف"]),
           ("كل الورود نباتات، وكل النباتات تحتاج ماءً.", "كل الورود تحتاج ماءً",
            ["كل النباتات ورود", "بعض الورود لا تحتاج ماءً", "الماء نبات"]),
           ("بعض الطلاب متفوقون، وكل المتفوقين مجتهدون.", "بعض الطلاب مجتهدون",
            ["كل الطلاب مجتهدون", "كل المجتهدين طلاب", "لا طالب مجتهد"]),
           ("كل القطط حيوانات، ولا حيوان يطير بلا أجنحة.", "كل القطط حيوانات",
            ["كل الحيوانات قطط", "القطط تطير", "لا قطة حيوان"]),
           ("كل المهندسين جامعيون، وبعض الجامعيين موظفون.", "كل المهندسين جامعيون",
            ["كل الجامعيين مهندسون", "كل المهندسين موظفون", "لا مهندس جامعي"]),
           ("لا طائر ثدييّ، وكل الحمام طيور.", "لا حمامة ثدييّة",
            ["كل الطيور حمام", "بعض الحمام ثدييّ", "الثدييات طيور"])]
    for prem, ans, dis in syl:
        out.append(gq(f"«{prem}» أي استنتاج صحيح قطعًا؟", ans, dis,
                      ["ارسم دوائر فِن: دائرة لكل مجموعة، والاحتواء يعني «كل».",
                       "الاستنتاج الصحيح هو ما يصح في كل الرسومات الممكنة لا في واحدة فقط.",
                       "كلمة «بعض» لا تُعمَّم أبدًا إلى «كل»، والعكس غير صحيح كذلك.",
                       f"الاستنتاج الوحيد الذي لا يحتمل الخطأ: {ans}."],
                      None, k=k, formatter=lambda x: x,
                      tip="أشهر فخ: قلب القضية («كل أ ب» لا تعني «كل ب أ»)."))
        k += 1

    return out
